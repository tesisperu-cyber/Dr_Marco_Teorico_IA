def obtener_unidad(nombre: str) -> dict:
    """Devuelve una unidad por su nombre; genera error claro si no existe."""
    if nombre not in UNIDADES:
        raise KeyError(f"No existe la unidad: {nombre}")
    return UNIDADES[nombre]
